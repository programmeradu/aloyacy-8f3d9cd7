const dicts = { en: en as Record<RoamKey, string>, el };

export function roamText(
  locale: "en" | "el",
  key: RoamKey,
  vars?: Record<string, string | number>,
) {
  const raw = dicts[locale][key] ?? en[key];
  return vars ? raw.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`)) : raw;
}

/** The core i18n hook plus `r()` for Roam copy. */
export function useRoamI18n() {
  const core = useI18n();
  const r = useCallback(
    (key: RoamKey, vars?: Record<string, string | number>) => roamText(core.locale, key, vars),
    [core.locale],
  );
  return { ...core, r };
}
