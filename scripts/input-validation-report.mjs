import fs from 'fs';
import path from 'path';
import { globSync } from 'glob';

const routesDir = path.resolve('src/routes/api/public');
const files = globSync('**/*.ts', { cwd: routesDir, absolute: true });

const report = [];

for (const file of files) {
  const content = fs.readFileSync(file, 'utf-8');
  
  // Exclude healthz/metrics and other pure endpoints if they don't read inputs
  // Let's actually just collect all safeParse calls.
  
  // We'll extract `Schema.safeParse(` or `Schema.parse(`
  const regex = /([A-Za-z0-9_]+Schema)\.(safeParse|parse)\(/g;
  
  const matches = [...content.matchAll(regex)];
  const relativePath = path.relative(routesDir, file);
  
  if (matches.length > 0) {
    report.push({
      file: relativePath,
      schemas: [...new Set(matches.map(m => m[1]))],
      hasValidation: true,
    });
  } else {
    // If it's a route that handles a request but has no validation, we record it
    // Wait, are there routes that genuinely take no input? (e.g. gbfs.json.ts, health.ts, indexnow.ts)
    // We'll mark them as no validation. We'll fail if it reads request but has no validation.
    // For simplicity, we just log it.
    report.push({
      file: relativePath,
      schemas: [],
      hasValidation: false,
    });
  }
}

// Generate docs/INPUT_VALIDATION.md
let md = `# Public API Input Validation Report\n\n`;
md += `This document is auto-generated by \`scripts/input-validation-report.mjs\`.\n\n`;
md += `| Route File | Schemas Validated |\n`;
md += `| :--- | :--- |\n`;

for (const entry of report) {
  if (entry.hasValidation) {
    md += `| \`${entry.file}\` | ${entry.schemas.map(s => `\`${s}\``).join(', ')} |\n`;
  } else {
    md += `| \`${entry.file}\` | *No validation* |\n`;
  }
}

fs.writeFileSync(path.resolve('docs/INPUT_VALIDATION.md'), md);

// Check if any route that should have validation is missing it? 
// We will just let the test `tests/input-validation.test.ts` handle failures.
console.log(`Generated docs/INPUT_VALIDATION.md with ${report.length} routes checked.`);

// Write JSON artifact
fs.writeFileSync(path.resolve('docs/INPUT_VALIDATION.json'), JSON.stringify(report, null, 2));
